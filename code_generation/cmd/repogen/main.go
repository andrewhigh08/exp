// Package main — это утилита для автоматической генерации кода (кодогенератор).
//
// Данный генератор анализирует исходный Go-файл, находит в нем структуры,
// помеченные специальным комментарием `//repogen:entity`, и создает для них
// базовую реализацию CRUD-репозитория (Get, Create, Update, Delete) поверх
// GORM v2 (gorm.io/gorm).
//
// ИСПОЛЬЗОВАНИЕ:
// Этот инструмент предназначен для вызова через `go generate`: имя исходного
// файла он берет из переменной окружения GOFILE, которую выставляет go generate.
//
// Генератор подключается к модулю как инструмент — tool-директивой в go.mod
// (Go 1.24+), поэтому ставить его в PATH через go install не нужно:
//
//	go get -tool ./cmd/repogen   // добавляет в go.mod строку `tool repogen/cmd/repogen`
//
// В файле, где определены ваши структуры данных (модели), добавьте директиву:
//
//	//go:generate go tool repogen
//
// После этого `go generate ./...` соберет генератор (сборка кэшируется) и
// создаст рядом с исходным файлом X.go файл X_gen.go с кодом репозиториев.
// Сгенерированный файл коммитят вместе с исходниками, чтобы пакет собирался
// без запуска go generate.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"log"
	"os"
	"reflect"
	"strconv"
	"strings"
	"text/template"
	"unicode"

	"golang.org/x/tools/go/ast/inspector"
	"golang.org/x/tools/imports"
	"gorm.io/gorm/schema"
	"gorm.io/gorm/utils"
)

// repositoryTemplate — это шаблон text/template для всего генерируемого файла:
// заголовок, package, один общий import и по репозиторию на каждую сущность.
// Первая строка — стандартная пометка сгенерированного кода
// (^// Code generated .* DO NOT EDIT\.$): по ней gopls, линтеры и GitHub
// понимают, что файл не правят руками. Пустая строка после нее нужна, чтобы
// пометка не стала doc-комментарием пакета.
// template.Must используется для того, чтобы паниковать при запуске, если шаблон некорректен.
var repositoryTemplate = template.Must(template.New("repogen").Parse(`// Code generated by repogen. DO NOT EDIT.

package {{ .Package }}

import "gorm.io/gorm"
{{- range .Entities }}

// {{ .EntityName }}Repository — CRUD-репозиторий для {{ .EntityName }} поверх GORM.
type {{ .EntityName }}Repository struct {
	db *gorm.DB
}

// New{{ .EntityName }}Repository создает репозиторий, работающий через db.
func New{{ .EntityName }}Repository(db *gorm.DB) {{ .EntityName }}Repository {
	return {{ .EntityName }}Repository{db: db}
}

// Get возвращает запись по первичному ключу.
func (r {{ .EntityName }}Repository) Get({{ .PrimaryName }} {{ .PrimaryType }}) (*{{ .EntityName }}, error) {
	entity := new({{ .EntityName }})
	// First (в отличие от Find) возвращает gorm.ErrRecordNotFound, если запись не найдена.
	err := r.db.Where("{{ .PrimarySQLName }} = ?", {{ .PrimaryName }}).First(entity).Error
	if err != nil {
		return nil, err
	}
	return entity, nil
}

// Create вставляет entity в таблицу; ключ, сгенерированный базой
// (автоинкремент), GORM записывает обратно в entity.
func (r {{ .EntityName }}Repository) Create(entity *{{ .EntityName }}) error {
	return r.db.Create(entity).Error
}

// Update обновляет запись с первичным ключом entity. Updates со структурой
// записывает только ненулевые поля. Без ключа (нулевое значение) GORM v2 не
// обновляет всю таблицу, а возвращает gorm.ErrMissingWhereClause.
func (r {{ .EntityName }}Repository) Update(entity *{{ .EntityName }}) error {
	return r.db.Model(entity).Updates(entity).Error
}

// Delete удаляет запись с первичным ключом entity. Без ключа GORM v2 не
// удаляет все записи, а возвращает gorm.ErrMissingWhereClause.
func (r {{ .EntityName }}Repository) Delete(entity *{{ .EntityName }}) error {
	return r.db.Delete(entity).Error
}
{{- end }}
`))

// repositoryGenerator хранит информацию, необходимую для генерации одного репозитория.
type repositoryGenerator struct {
	typeSpec   *ast.TypeSpec
	structType *ast.StructType
}

// templateParams — данные шаблона для одного репозитория.
type templateParams struct {
	EntityName     string // имя структуры: User
	PrimaryName    string // имя параметра Get: userID
	PrimarySQLName string // колонка первичного ключа: user_id
	PrimaryType    string // Go-тип первичного ключа: uint
}

// structField — одно поле структуры. У ast.Field может быть несколько имен
// (`A, B int`), поэтому поле описываем парой «имя + тип» и настройками тега gorm.
type structField struct {
	name     string
	typ      ast.Expr
	settings map[string]string
}

// gormSettings разбирает тег gorm тем же парсером, что и сам GORM: настройки
// разделены ';', ключи нечувствительны к регистру и приводятся к верхнему
// (gorm:"column:id;primaryKey" -> {"COLUMN": "id", "PRIMARYKEY": "PRIMARYKEY"}).
func gormSettings(tag *ast.BasicLit) map[string]string {
	var gormTag string
	if tag != nil {
		// tag.Value — литерал из исходника вместе с кавычками (`...` или "..."):
		// strconv.Unquote снимает их (корректность литерала уже проверил парсер),
		// а reflect.StructTag достает значение по ключу.
		raw, _ := strconv.Unquote(tag.Value)
		gormTag = reflect.StructTag(raw).Get("gorm")
	}
	return schema.ParseTagSetting(gormTag, ";")
}

// column возвращает имя колонки так же, как GORM v2: из настройки column тега,
// а без нее — по стратегии именования GORM по умолчанию (snake_case с учетом
// аббревиатур: UserID -> user_id, HTTPServer -> http_server). Если в
// gorm.Config задана своя NamingStrategy, колонку стоит указать в теге явно.
func (f structField) column() string {
	if column := f.settings["COLUMN"]; column != "" {
		return column
	}
	return schema.NamingStrategy{}.ColumnName("", f.name)
}

// fields возвращает экспортируемые именованные поля структуры: неэкспортируемые
// GORM не сохраняет. Поля встроенных структур (например, gorm.Model) генератор
// не видит — для этого пришлось бы загружать и анализировать их пакеты.
func (r repositoryGenerator) fields() []structField {
	var fields []structField
	for _, field := range r.structType.Fields.List {
		settings := gormSettings(field.Tag)
		for _, name := range field.Names { // у встроенного поля имен нет
			if name.IsExported() {
				fields = append(fields, structField{name: name.Name, typ: field.Type, settings: settings})
			}
		}
	}
	return fields
}

// primaryField находит первичный ключ по правилам GORM v2: поле с настройкой
// primaryKey (или primary_key из GORM v1) в теге gorm, а если таких нет —
// поле ID (или поле с колонкой id).
func (r repositoryGenerator) primaryField() (structField, error) {
	fields := r.fields()
	var keys []structField
	var keyNames []string
	for _, field := range fields {
		// CheckTruth — та же проверка, что в GORM: настройка задана и не равна "false".
		if utils.CheckTruth(field.settings["PRIMARYKEY"], field.settings["PRIMARY_KEY"]) {
			keys = append(keys, field)
			keyNames = append(keyNames, field.name)
		}
	}

	switch len(keys) {
	case 1:
		return keys[0], nil
	case 0:
		for _, field := range fields {
			if field.name == "ID" || field.column() == "id" {
				return field, nil
			}
		}
		return structField{}, fmt.Errorf("не найден первичный ключ (gorm:\"primaryKey\" или поле ID) в структуре %s", r.typeSpec.Name.Name)
	default:
		return structField{}, fmt.Errorf("составной первичный ключ (%s) в структуре %s не поддерживается: Get принимает одно значение ключа",
			strings.Join(keyNames, ", "), r.typeSpec.Name.Name)
	}
}

// reservedNames — идентификаторы, которые использует сгенерированный Get:
// параметр с таким именем перекрыл бы их, и код бы не скомпилировался.
var reservedNames = map[string]bool{"r": true, "entity": true, "err": true, "new": true, "nil": true}

// paramName делает из имени поля имя параметра: переводит в нижний регистр
// первую букву, а ведущую аббревиатуру — целиком (UserID -> userID, ID -> id,
// SKU -> sku, URLKey -> urlKey). Если получилось ключевое слово (Type -> type)
// или имя, занятое в теле Get (reservedNames или имя самой структуры),
// используется нейтральное "key".
func paramName(fieldName, entityName string) string {
	runes := []rune(fieldName)
	upper := 0 // длина ведущей последовательности заглавных букв
	for upper < len(runes) && unicode.IsUpper(runes[upper]) {
		upper++
	}
	if upper > 1 && upper < len(runes) && unicode.IsLower(runes[upper]) {
		upper-- // в URLKey буква K уже начинает следующее слово
	}
	for i := range upper {
		runes[i] = unicode.ToLower(runes[i])
	}

	name := string(runes)
	if token.IsKeyword(name) || reservedNames[name] || name == entityName {
		return "key"
	}
	return name
}

// params готовит параметры для передачи в шаблон.
func (r repositoryGenerator) params() (templateParams, error) {
	// Находим поле, которое является первичным ключом.
	primary, err := r.primaryField()
	if err != nil {
		return templateParams{}, err
	}
	return templateParams{
		EntityName:     r.typeSpec.Name.Name,
		PrimaryName:    paramName(primary.name, r.typeSpec.Name.Name),
		PrimarySQLName: primary.column(),              // Получаем имя колонки из тега или по имени поля.
		PrimaryType:    types.ExprString(primary.typ), // Тип поля как в исходнике: "uint", "uuid.UUID".
	}, nil
}

// hasEntityMarker сообщает, есть ли в комментарии строка //repogen:entity.
// Это директива в стиле //go:generate (без пробела после //), а такие строки
// CommentGroup.Text() отбрасывает, поэтому перебираем строки комментария.
func hasEntityMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, comment := range doc.List {
		if comment.Text == "//repogen:entity" {
			return true
		}
	}
	return false
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("repogen: ")

	// `go generate` устанавливает несколько переменных окружения. GOFILE - одна из них:
	// имя файла с директивой; рабочий каталог при этом — каталог пакета.
	path := os.Getenv("GOFILE")
	if path == "" {
		log.Fatal("Переменная окружения GOFILE должна быть установлена. Запустите через `go generate`.")
	}

	// 1. Парсим исходный файл в AST.
	fset := token.NewFileSet()
	astInFile, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		log.Fatalf("ошибка парсинга файла %s: %v", path, err)
	}

	// 2. Ищем задания для генерации.
	// inspector из golang.org/x/tools обходит AST и вызывает функцию только для
	// узлов из фильтра. Возвращая false, не спускаемся внутрь узла: нужны только
	// объявления верхнего уровня, а не локальные типы в телах функций.
	// (Для одного файла хватило бы и цикла по astInFile.Decls; inspector
	// выгоден, когда файлов и узлов много.)
	var genTasks []repositoryGenerator
	i := inspector.New([]*ast.File{astInFile})
	filter := []ast.Node{
		(*ast.FuncDecl)(nil), // Функции нужны только для того, чтобы не заходить в их тела.
		(*ast.GenDecl)(nil),  // Общие объявления (type, var, const, import).
	}
	i.Root().Inspect(filter, func(c inspector.Cursor) (descend bool) {
		genDecl, ok := c.Node().(*ast.GenDecl)
		// Проверяем, что это объявление типа (`type ...`).
		if !ok || genDecl.Tok != token.TYPE {
			return false
		}
		for _, spec := range genDecl.Specs {
			typeSpec := spec.(*ast.TypeSpec) // в объявлении type все спецификации — *ast.TypeSpec
			// И что это структура (`struct { ... }`).
			structType, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				continue
			}
			// Ищем "магический" комментарий: над `type User struct` он относится
			// ко всему объявлению, а внутри группы `type ( ... )` — к отдельному типу.
			doc := typeSpec.Doc
			if doc == nil {
				doc = genDecl.Doc
			}
			if hasEntityMarker(doc) {
				genTasks = append(genTasks, repositoryGenerator{
					typeSpec:   typeSpec,
					structType: structType,
				})
			}
		}
		return false
	})

	if len(genTasks) == 0 {
		log.Println("Не найдено структур с комментарием //repogen:entity. Генерация не требуется.")
		return
	}

	// 3. Готовим параметры шаблона для каждого найденного задания.
	data := struct {
		Package  string // Имя пакета должно совпадать с исходным.
		Entities []templateParams
	}{Package: astInFile.Name.Name}
	for _, task := range genTasks {
		params, err := task.params()
		if err != nil {
			log.Fatalf("ошибка генерации для %s: %v", task.typeSpec.Name.Name, err)
		}
		data.Entities = append(data.Entities, params)
	}

	// 4. Выполняем шаблон: сразу весь файл, поэтому заголовок и import в нем
	// ровно по одному, сколько бы сущностей ни было.
	var buf bytes.Buffer
	if err := repositoryTemplate.Execute(&buf, data); err != nil {
		log.Fatalf("ошибка выполнения шаблона: %v", err)
	}

	// 5. Форматируем результат так же, как goimports: imports.Process разбирает
	// код (заодно проверяя синтаксис), форматирует его как gofmt и добавляет
	// недостающие импорты. Например, для ключа типа uuid.UUID нужный импорт
	// берется из исходного файла — соседа по пакету.
	outFileName := strings.TrimSuffix(path, ".go") + "_gen.go"
	src, err := imports.Process(outFileName, buf.Bytes(), nil)
	if err != nil {
		log.Fatalf("ошибка форматирования сгенерированного кода: %v\n%s", err, buf.Bytes())
	}

	// 6. Записываем файл целиком: до этого момента на диске ничего не меняется,
	// так что при ошибке не останется наполовину записанного файла.
	if err := os.WriteFile(outFileName, src, 0o644); err != nil {
		log.Fatalf("ошибка записи в файл %s: %v", outFileName, err)
	}

	log.Printf("Успешно сгенерирован файл: %s", outFileName)
}
