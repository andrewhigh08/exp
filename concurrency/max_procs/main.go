// Package main демонстрирует поведение планировщика Go и недетерминизм
// при выполнении горутин, особенно при ограничении до одного потока ОС.
package main

import (
	"fmt"
	"runtime"
	"sync"
)

// runWorkers запускает 5 горутин, каждая из которых печатает свой ID.
func runWorkers(description string) {
	fmt.Printf("\n--- %s ---\n", description)

	var wg sync.WaitGroup
	wg.Add(5)

	for i := range 5 {
		// Передаем `i` как аргумент. С Go 1.22 у каждой итерации своя `i`, поэтому замыкание
		// могло бы использовать ее и напрямую — каждая горутина все равно получит свой ID
		// (до Go 1.22 без аргумента горутины видели бы общую переменную цикла).
		go func(workerID int) {
			defer wg.Done()
			// runtime.Gosched() можно было бы использовать здесь, чтобы "подсказать"
			// планировщику, что можно переключиться на другую горутину.
			// Но даже без этого, вызов fmt.Printf (операция I/O) является
			// точкой прерывания, где планировщик может сменить контекст.
			fmt.Printf("%d ", workerID)
		}(i)
	}

	wg.Wait()
	fmt.Println()
}

func main() {
	// --- Сценарий 1: Ограничение до одного потока ОС ---
	// runtime.GOMAXPROCS(1) разрешает исполнять Go-код одновременно только одному
	// потоку операционной системы (у планировщика остается один P). Это означает,
	// что в каждый момент времени может исполняться только одна горутина.
	// Планировщик будет "переключать" горутины по очереди. (Потоков ОС у процесса
	// при этом может быть больше: потоки, заблокированные в системных вызовах,
	// в лимит GOMAXPROCS не входят.)
	//
	// Ожидаемый результат: Порядок вывода чисел (0 1 2 3 4) НЕ ГАРАНТИРОВАН.
	// Пример вывода в комментариях (4 0 1 2 3) показывает, что планировщик
	// может запустить последнюю горутину (с ID 4) раньше, чем другие,
	// которые уже были готовы к выполнению. Порядок задает планировщик,
	// а язык его не гарантирует (подробнее — в комментарии в конце файла).
	oldMaxProcs := runtime.GOMAXPROCS(1)
	runWorkers("Выполнение на одном потоке (GOMAXPROCS=1)")

	// --- Сценарий 2: Использование всех доступных потоков ---
	// Возвращаем прежнее значение GOMAXPROCS. По умолчанию оно равно значению переменной
	// окружения GOMAXPROCS, а если она не задана — числу логических CPU, доступных процессу
	// (с Go 1.25 на Linux — с учетом лимита CPU в cgroup, поэтому в контейнере оно может быть
	// меньше runtime.NumCPU()). С Go 1.25 рантайм еще и сам обновляет значение по умолчанию,
	// когда эти лимиты меняются, но явный вызов runtime.GOMAXPROCS(n) (как и переменная
	// окружения GOMAXPROCS) автообновление отключает; вернуть поведение по умолчанию
	// целиком можно через runtime.SetDefaultGOMAXPROCS().
	runtime.GOMAXPROCS(oldMaxProcs)
	// Печатаем фактическое значение: runtime.GOMAXPROCS(0) только читает его, не меняя.
	runWorkers(fmt.Sprintf("Выполнение на %d потоках (по умолчанию)", runtime.GOMAXPROCS(0)))
	// В этом случае горутины могут выполняться по-настоящему параллельно на разных ядрах,
	// но порядок вывода все равно не гарантирован и зависит от сложного взаимодействия
	// планировщика и операционной системы.

	fmt.Println("\nВывод: Порядок выполнения горутин не гарантирован, и корректность программы не должна от него зависеть: нужный порядок задается только явной синхронизацией (каналы, мьютексы и т.д.).")
}

/*
Пример возможного вывода при GOMAXPROCS(1):
4 0 1 2 3

Это происходит потому, что цикл for может успеть запуститься и поставить все 5 горутин
в очередь на выполнение до того, как первая из них реально начнет печатать.
Планировщик может выбрать последнюю поставленную в очередь горутину для выполнения первой.

В текущей реализации так и происходит: только что созданная горутина попадает в слот
runnext своего P и запускается следующей, а предыдущая уходит в конец обычной очереди
(FIFO). Поэтому при одном P вывод обычно стабилен: 4, затем 0 1 2 3. Это деталь
реализации, а не гарантия языка: например, под детектором гонок (-race) планировщик
намеренно перемешивает порядок, и вывод меняется от запуска к запуску.
*/
