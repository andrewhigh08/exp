package main

import "fmt"

// addDigits складывает два неотрицательных числа, заданных массивами цифр
// (старший разряд первым), и возвращает сумму в том же виде.
//
// Время: O(max(n, m)) — один проход по более длинному числу плюс не более одной
// итерации на финальный перенос (n=len(a), m=len(b)).
// Память: O(max(n, m)) всего (единственная аллокация res), из них O(1)
// дополнительной — результат отдаётся срезом того же массива без копии.
func addDigits(a, b []int) []int {
	// пустые входы - это число 0
	if len(a) == 0 && len(b) == 0 {
		return []int{0}
	}

	i := len(a) - 1 // указатель на младший разряд a
	j := len(b) - 1 // указатель на младший разряд b

	// результат: максимум max(len(a), len(b))+1 разрядов (+1 на возможный перенос)
	res := make([]int, max(len(a), len(b))+1)
	k := len(res) - 1 // пишем с конца
	perenos := 0
	// идём с младших разрядов, выравнивая разные длины по ходу
	for i >= 0 || j >= 0 || perenos > 0 {
		sum := perenos
		if i >= 0 {
			sum += a[i]
			i--
		}
		if j >= 0 {
			sum += b[j]
			j--
		}
		res[k] = sum % 10
		perenos = sum / 10
		k--
	}
	// k+1 — индекс первой записанной цифры; срезаем неиспользованный префикс
	return res[k+1:]
}

func main() {
	// 123 + 456 = 579
	fmt.Println(addDigits([]int{1, 2, 3}, []int{4, 5, 6})) // [5 7 9]
	// 544 + 456 = 1000
	fmt.Println(addDigits([]int{5, 4, 4}, []int{4, 5, 6})) // [1 0 0 0]
	// 99 + 1 = 100 (разная длина)
	fmt.Println(addDigits([]int{9, 9}, []int{1})) // [1 0 0]
	// 0 + 0 = 0 (пустые входы)
	fmt.Println(addDigits([]int{}, []int{})) // [0]
}
