package main

import "fmt"

// compareVersions сравнивает две строки-версии формата "v" + числа/точки.
// Возвращает:
//
//	 0  если версии равны,
//	 1  если v1 МЕНЬШЕ v2  (по примеру из условия: 44<45 -> 1),
//	-1  если v1 БОЛЬШЕ v2.
//
// Знак намеренно противоположен стандартному cmp — см. условие задачи.
// ok=false, если любая из строк не прошла валидацию формата.
//
// Время: O(n+m) — валидация плюс посегментный проход по обеим строкам;
// n=len(v1), m=len(v2).
// Память: O(1) — парсинг на месте, без аллокаций и срезов.
func compareVersions(v1, v2 string) (res int, ok bool) {
	// Валидируем обе строки: префикс 'v', далее только цифры и точки.
	if !validate(v1) || !validate(v2) {
		return 0, false
	}

	// Идём по обеим строкам с позиции 1 (пропускаем 'v'),
	// посегментно сравнивая накопленные числа. Недостающие хвостовые
	// сегменты трактуем как 0 (v1 == v1.0).
	i, j := 1, 1
	n, m := len(v1), len(v2)
	for i < n || j < m {
		a, ni := segment(v1, i, n) // число сегмента и новая позиция
		b, nj := segment(v2, j, m)
		if a < b {
			return 1, true // v1 < v2
		}
		if a > b {
			return -1, true // v1 > v2
		}
		i, j = ni, nj
	}
	return 0, true // все сегменты равны
}

// validate проверяет формат: первая руна 'v', далее только '0'-'9' и '.'.
// Дополнительно требуем, чтобы после 'v' был хотя бы один символ.
func validate(s string) bool {
	if len(s) < 2 || s[0] != 'v' {
		return false
	}
	for r := 1; r < len(s); r++ {
		if s[r] == '.' {
			continue
		}
		if s[r] < '0' || s[r] > '9' {
			return false
		}
	}
	return true
}

// segment парсит одно число начиная с позиции i (накопление d=c-'0'),
// останавливается на '.' или конце строки. Возвращает значение сегмента
// и позицию следующего сегмента (за точкой). Пустой сегмент (например "v..1"
// или хвостовая точка) даёт значение 0.
func segment(s string, i, n int) (val, next int) {
	for i < n && s[i] != '.' {
		val = val*10 + int(s[i]-'0') // парсинг без strconv
		i++
	}
	if i < n && s[i] == '.' {
		i++ // перешагиваем точку, позиционируемся на начало след. сегмента
	}
	return val, i
}

func main() {
	res1, _ := compareVersions("v11.22.44", "v11.22.45")
	res2, _ := compareVersions("v11.22.44", "v11.22.44")
	fmt.Println(res1, res2) // 1 0
}
