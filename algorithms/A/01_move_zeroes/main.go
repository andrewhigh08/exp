package main

import "fmt"

// moveZeroes сдвигает все нули в конец слайса на месте,
// сохраняя относительный порядок ненулевых элементов.
// Два указателя: w — позиция записи, i — сканер.
//
// Время: O(N) — два последовательных прохода по слайсу (сканирование + забивание
// хвоста нулями), каждый не длиннее N (N=len(a)).
// Память: O(1) дополнительной — работа на месте, только два индекса w и i,
// без вспомогательных буферов.
func moveZeroes(a []int) {
	w := 0 // позиция, куда положим следующий ненулевой элемент
	for i := 0; i < len(a); i++ {
		if a[i] != 0 {
			a[w] = a[i] // переносим ненулевой элемент в начало
			w++
		}
	}
	// хвост [w..len) забиваем нулями
	for ; w < len(a); w++ {
		a[w] = 0
	}
}

func main() {
	a := []int{7, 3, 0, 0, 0, 2, 4, 0, 5, 19}
	moveZeroes(a)
	fmt.Println(a) // [7 3 2 4 5 19 0 0 0 0]

	// несколько проверок граничных случаев
	cases := [][]int{
		{},                 // пустой
		{0},                // один ноль
		{5},                // один ненулевой
		{0, 0, 0},          // все нули
		{1, 2, 3},          // нулей нет
		{0, 1, 0, 2, 0, 3}, // чередование
		{-1, 0, -2, 0, 3},  // отрицательные значения
	}
	for _, c := range cases {
		moveZeroes(c)
		fmt.Println(c)
	}
}
