// Package main содержит решение задачи по упрощению абсолютного пути в Unix-стиле.
package main

import (
	"fmt"
	"strings"
)

// Исходная задача:
// Дан абсолютный путь до файла или папки (Unix-style) - необходимо упростить его.
//
// Обозначения:
// "/" - разделитель каталогов.
// ".." - выход на каталог выше.
// "." - текущий каталог.
//
// Формат результата:
// - Путь начинается с косой черты '/'.
// - Каталоги разделяются одинарной косой чертой '/'.
// - Путь не заканчивается символом '/'.

// simplifyPath упрощает заданный абсолютный путь.
//
// Алгоритм использует стек для эффективного построения канонического пути.
// Стек — идеальная структура данных для этой задачи, так как переходы "вверх" ("..")
// являются операцией LIFO (Last-In, First-Out), что соответствует поведению стека.
func simplifyPath(path string) string {
	// 1. Разделяем строку по "/", чтобы получить компоненты пути.
	// Например, "/a/./b/../c/" -> ["", "a", ".", "b", "..", "c", ""]
	parts := strings.Split(path, "/")

	// 2. Используем срез (slice) в качестве стека для хранения "чистых" компонентов пути.
	var stack []string

	// 3. Проходим по всем компонентам пути.
	for _, part := range parts {
		switch part {
		case "", ".":
			// Игнорируем пустые строки (возникают из-за двойных слешей, например, "//")
			// и точки (указание на текущий каталог).
			continue
		case "..":
			// ".." означает переход на уровень выше.
			// Для этого мы просто "выталкиваем" последний элемент из стека.
			// Проверяем, что стек не пуст, так как нельзя подняться выше корневого каталога.
			if len(stack) > 0 {
				stack = stack[:len(stack)-1]
			}
		default:
			// Любой другой компонент — это имя каталога.
			// "Вталкиваем" его в стек.
			stack = append(stack, part)
		}
	}

	// 4. Собираем итоговый путь из компонентов, оставшихся в стеке.
	// Мы соединяем их через "/" и добавляем ведущий слеш для абсолютного пути.
	return "/" + strings.Join(stack, "/")
}

func main() {
	testCases := map[string]string{
		"/etc/":                      "/etc",
		"/../../../../":              "/",
		"/first/second/../../third/": "/third",
		"/first/./second/./third":    "/first/second/third",
		"/a/./b/../../c/":            "/c",
		"/home//foo/":                "/home/foo",
		"/":                          "/",
		"/a/b/c":                     "/a/b/c",
	}

	fmt.Println("--- Тестирование функции simplifyPath ---")
	allPassed := true
	for path, expected := range testCases {
		result := simplifyPath(path)
		if result == expected {
			fmt.Printf("✅ OK:     Input: '%-30s' -> Output: '%s'\n", path, result)
		} else {
			allPassed = false
			fmt.Printf("❌ ERROR:  Input: '%-30s' -> Output: '%s', Expected: '%s'\n", path, result, expected)
		}
	}
	fmt.Println("---------------------------------------")
	if allPassed {
		fmt.Println("🎉 Все тесты пройдены успешно!")
	} else {
		fmt.Println("❗️ Некоторые тесты не пройдены.")
	}
}
